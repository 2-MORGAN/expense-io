import { randomUUID } from 'node:crypto'
import { escapeIdentifier, escapeLiteral } from 'pg'
import { expect, test } from './support/fixtures'
import { db } from './support/db'

// ADR-001 ERR-01 / ADR-004 §3: inject a real server failure, never a production test endpoint.
// The trigger affects only this test's note, and is removed even if the request/assertion fails.
test('[ERR-01] panne serveur injectée → problème générique sans détail interne', async ({ org, apiAs }) => {
  const employee = await apiAs(org.employee)
  const manager = await apiAs(org.manager)
  const note = await employee.submitNote({ description: 'ERR-01' })
  const suffix = randomUUID().replaceAll('-', '')
  const functionName = escapeIdentifier(`e2e_err_${suffix}`)
  const triggerName = escapeIdentifier(`e2e_err_trigger_${suffix}`)
  const internalMessage = 'ERR01_INTERNAL_SQL_password_private'
  try {
    // Identifiers and UUID are generated by this test, never supplied by an API caller.
    await db().query(`CREATE FUNCTION ${functionName}() RETURNS trigger LANGUAGE plpgsql AS $$
      BEGIN RAISE EXCEPTION '${internalMessage}'; END $$`)
    // eslint-disable-next-line no-restricted-syntax -- PostgreSQL DDL cannot bind identifiers; generated names and UUID literals are escaped.
    await db().query(`CREATE TRIGGER ${triggerName} BEFORE UPDATE ON expense_notes
      FOR EACH ROW WHEN (OLD.id = ${escapeLiteral(note.id)}::uuid) EXECUTE FUNCTION ${functionName}()`)
    const response = await manager.managerDecide(note.id, 'approve')
    expect(response.status()).toBe(500)
    expect(response.headers()['content-type']).toContain('application/problem+json')
    const body = await response.json()
    expect(body).toEqual({
      type: '/problems/internal-error', title: 'Internal server error', status: 500,
      detail: 'An unexpected error occurred.', code: 'INTERNAL_ERROR',
      error: 'An unexpected error occurred.', requestId: expect.any(String),
    })
    expect(body.requestId).toMatch(/^[0-9a-f]{8}-[0-9a-f-]{27}$/i)
    expect(response.headers()['x-request-id']).toBe(body.requestId)
    expect(JSON.stringify(body)).not.toMatch(/ERR01_INTERNAL|stack|password|\.ts:|node_modules/)
    expect((await employee.notes()).find(item => item.id === note.id)?.status).toBe('pending')
  } finally {
    await db().query(`DROP TRIGGER IF EXISTS ${triggerName} ON expense_notes`)
    await db().query(`DROP FUNCTION IF EXISTS ${functionName}()`)
  }
})

test('[ERR-02] refus métier → même format, codes stables et textes historiques préservés', async ({ org, apiAs, request }) => {
  const employee = await apiAs(org.employee)
  const manager = await apiAs(org.manager)
  const note = await employee.submitNote()
  const refused = [
    [await request.get('/api/expense-notes'), 401, 'AUTHENTICATION_REQUIRED', 'Unauthorized'],
    [await employee.request.get('/api/manager/expense-notes'), 403, 'FORBIDDEN', 'Unauthorized'],
    [await manager.managerDecide(randomUUID(), 'approve'), 404, 'RESOURCE_NOT_FOUND', 'Not found'],
  ] as const
  expect((await manager.managerDecide(note.id, 'approve')).status()).toBe(200)
  const conflict = await manager.managerDecide(note.id, 'reject')
  for (const [response, status, code, legacy] of [...refused, [conflict, 409, 'ALREADY_DECIDED', 'Already decided'] as const]) {
    expect(response.status()).toBe(status)
    expect(response.headers()['content-type']).toContain('application/problem+json')
    const body = await response.json()
    expect(body).toMatchObject({ status, code, error: legacy, requestId: expect.any(String) })
    expect(response.headers()['x-request-id']).toBe(body.requestId)
  }
})

test('[ERR-03] le front traduit le code et protège aussi les codes inconnus', async ({ org, pageAs }) => {
  const page = await pageAs(org.manager)
  for (const [code, message] of [
    ['FORBIDDEN', 'Tu n’as pas les droits nécessaires pour cette action.'],
    ['FUTURE_CODE', 'Une erreur est survenue. Réessaie plus tard.'],
  ]) {
    await page.route('**/api/manager/expense-notes', route => route.fulfill({
      status: 403, contentType: 'application/problem+json',
      body: JSON.stringify({ code, detail: 'PRIVATE ENGLISH DETAIL', error: 'PRIVATE LEGACY MESSAGE' }),
    }))
    await page.goto('/manager')
    await expect(page.getByRole('main').getByRole('alert')).toHaveText(message)
    await page.unroute('**/api/manager/expense-notes')
  }
})
